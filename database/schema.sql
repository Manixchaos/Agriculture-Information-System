-- Agriculture Information System
-- Supabase PostgreSQL schema. Run in Supabase SQL Editor.

CREATE TABLE IF NOT EXISTS app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'Staff' CHECK (role IN ('Administrator', 'Staff')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS crop_categories (
    category_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS seasons (
    season_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS soil_types (
    soil_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    soil_type_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS irrigation_types (
    irrigation_type_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    irrigation_type_name VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS planting_statuses (
    status_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS quality_grades (
    grade_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_name VARCHAR(30) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS harvest_remarks (
    remark_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remark_description VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS farmers (
    farmer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    contact_number VARCHAR(20),
    address VARCHAR(150) NOT NULL,
    date_registered DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT farmers_contact_not_blank CHECK (contact_number IS NULL OR length(trim(contact_number)) > 0)
);

CREATE TABLE IF NOT EXISTS farms (
    farm_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES farmers(farmer_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    farm_name VARCHAR(100) NOT NULL,
    location VARCHAR(150) NOT NULL,
    area_hectares NUMERIC(8,2) NOT NULL CHECK (area_hectares > 0),
    soil_type_id SMALLINT REFERENCES soil_types(soil_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    irrigation_type_id SMALLINT REFERENCES irrigation_types(irrigation_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS crops (
    crop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name VARCHAR(80) NOT NULL,
    variety VARCHAR(80) NOT NULL,
    category_id SMALLINT NOT NULL REFERENCES crop_categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    growing_period_days INTEGER NOT NULL CHECK (growing_period_days > 0),
    recommended_season_id SMALLINT REFERENCES seasons(season_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT crops_name_variety_unique UNIQUE (crop_name, variety)
);

CREATE TABLE IF NOT EXISTS plantings (
    planting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT NOT NULL REFERENCES farms(farm_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    crop_id BIGINT NOT NULL REFERENCES crops(crop_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    planting_date DATE NOT NULL,
    area_planted NUMERIC(8,2) NOT NULL CHECK (area_planted > 0),
    seed_quantity_kg NUMERIC(10,2) NOT NULL CHECK (seed_quantity_kg >= 0),
    expected_harvest_date DATE NOT NULL,
    status_id SMALLINT NOT NULL REFERENCES planting_statuses(status_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT planting_date_order CHECK (expected_harvest_date >= planting_date)
);

CREATE TABLE IF NOT EXISTS harvests (
    harvest_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planting_id BIGINT NOT NULL REFERENCES plantings(planting_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    harvest_date DATE NOT NULL,
    quantity_kg NUMERIC(12,2) NOT NULL CHECK (quantity_kg >= 0),
    selling_price_per_kg NUMERIC(10,2) NOT NULL CHECK (selling_price_per_kg >= 0),
    grade_id SMALLINT REFERENCES quality_grades(grade_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    remark_id SMALLINT REFERENCES harvest_remarks(remark_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    notes VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_farms_farmer ON farms(farmer_id);
CREATE INDEX IF NOT EXISTS idx_plantings_farm ON plantings(farm_id);
CREATE INDEX IF NOT EXISTS idx_plantings_crop ON plantings(crop_id);
CREATE INDEX IF NOT EXISTS idx_plantings_status ON plantings(status_id);
CREATE INDEX IF NOT EXISTS idx_harvests_planting ON harvests(planting_id);
CREATE INDEX IF NOT EXISTS idx_harvests_date ON harvests(harvest_date);

-- Keep updated_at current on updates.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['app_users','farmers','farms','crops','plantings','harvests']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS trg_%I_updated_at ON %I', t, t);
        EXECUTE format('CREATE TRIGGER trg_%I_updated_at BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()', t, t);
    END LOOP;
END $$;
